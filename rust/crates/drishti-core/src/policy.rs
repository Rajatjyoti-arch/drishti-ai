//! Policy, execution boundary, and security invariant models.
//!
//! Represents typed execution requests submitted by the Python Intelligence Layer
//! and evaluated internally by the Rust Security Kernel.
//!
//! Important: Raw credentials and bearer tokens are strictly forbidden from these models.
//! Python references credentials by symbolic reference (e.g., "agency_b_session"),
//! and only the Rust Credential Broker attaches real secrets in memory immediately before transmission.

use crate::identity::{TenantContext, TenantId};
use chrono::{DateTime, Utc};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::fmt;
use std::str::FromStr;

/// Canonical B2B Travel Security Invariant Identifiers.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, JsonSchema)]
pub enum InvariantId {
    /// I-01: Multi-tenant data and state isolation (BOLA / IDOR)
    #[serde(rename = "I-01")]
    I01,
    /// I-02: Tariff and price integrity across hold-to-confirm transitions
    #[serde(rename = "I-02")]
    I02,
    /// I-03: Inventory hold lifecycle and cancellation concurrency
    #[serde(rename = "I-03")]
    I03,
    /// I-04: Deprecated or shadow API boundary enforcement
    #[serde(rename = "I-04")]
    I04,
}

impl fmt::Display for InvariantId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::I01 => write!(f, "I-01"),
            Self::I02 => write!(f, "I-02"),
            Self::I03 => write!(f, "I-03"),
            Self::I04 => write!(f, "I-04"),
        }
    }
}

impl FromStr for InvariantId {
    type Err = PolicyModelError;
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "I-01" | "i-01" | "I01" => Ok(Self::I01),
            "I-02" | "i-02" | "I02" => Ok(Self::I02),
            "I-03" | "i-03" | "I03" => Ok(Self::I03),
            "I-04" | "i-04" | "I04" => Ok(Self::I04),
            other => Err(PolicyModelError::InvalidInvariant(other.to_string())),
        }
    }
}

/// Permitted policy actions determined by the Policy Gate.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum PolicyAction {
    /// Request meets all safety boundaries and budgets; execution permitted
    Allow,
    /// Request violates authorization contract, scope, or destination boundary
    Block,
    /// Request temporarily throttled due to rate or concurrency budget saturation
    Throttle,
    /// Request targets an elevated or high-risk operation requiring human sign-off
    RequiresApproval,
    /// Emergency stop condition triggered; all active testing halted
    EmergencyStop,
}

/// Outgoing test request submitted by the Python Intelligence Layer to the Rust Security Kernel.
/// The Rust kernel independently validates scope, rate limits, and budgets before executing.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct OutgoingTestRequest {
    /// Unique identifier for this test request probe
    pub request_id: String,
    /// Parent test suite or finding hypothesis ID
    pub test_id: String,
    /// Destination target URL (must resolve to authorized domain allowlist)
    pub target_url: String,
    /// HTTP method (GET, POST, PUT, DELETE, PATCH)
    pub method: String,
    /// Request headers (excluding raw authorization tokens)
    #[serde(default)]
    pub headers: HashMap<String, String>,
    /// Optional serialized request body
    #[serde(skip_serializing_if = "Option::is_none")]
    pub body: Option<String>,
    /// Optional tenant context (persona) simulating the request
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tenant_context: Option<TenantContext>,
    /// Symbolic credential alias to be resolved by the Rust Credential Broker
    #[serde(skip_serializing_if = "Option::is_none")]
    pub credential_ref: Option<String>,
    /// Security invariant being tested
    #[serde(skip_serializing_if = "Option::is_none")]
    pub invariant_candidate: Option<InvariantId>,
    /// Timeout in milliseconds (capped by authoritative test budgets)
    #[serde(default = "default_timeout_ms")]
    pub timeout_ms: u64,
}

fn default_timeout_ms() -> u64 {
    5000
}

/// Internal cryptographic policy decision generated by the Rust Policy Gate.
/// Bound immutably to the exact request payload and method.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct PolicyDecision {
    /// Policy gate evaluation outcome
    pub action: PolicyAction,
    /// Human-readable explanation of decision
    pub reason: String,
    /// Name of the specific policy boundary rule matched
    pub rule_matched: String,
    /// Cryptographic single-use nonce binding this decision to the exact request
    pub decision_nonce: String,
    /// SHA-256 digest of the bound request parameters (method, url, body)
    pub bound_request_digest: String,
    /// Timestamp of evaluation
    pub evaluated_at: DateTime<Utc>,
}

/// Sanitized execution result returned by Rust to Python after network transmission.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct ExecutionResult {
    /// Matching test request ID
    pub request_id: String,
    /// HTTP status code returned by target
    pub status_code: u16,
    /// Response headers (scrubbed of sensitive internal cookies)
    pub headers: HashMap<String, String>,
    /// Sanitized response body (with automated PII and secret redaction)
    pub sanitized_body: String,
    /// Round-trip execution latency in milliseconds
    pub latency_ms: u64,
    /// Cryptographic decision nonce confirming execution passed through the Policy Gate
    pub policy_decision_nonce: String,
    /// SHA-256 hash of the complete raw response frame stored in the tamper-evident ledger
    pub response_digest: String,
}

/// Synthetic canary token definition for multi-tenant isolation testing.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CanaryDefinition {
    /// Unique canary token string (e.g., "drishti_canary_7f3b8a1c")
    pub token: String,
    /// Tenant that legitimately owns the object containing the canary
    pub owning_tenant: TenantId,
    /// Invariant ID verified by this canary
    pub invariant: InvariantId,
    /// Timestamp when canary was generated and injected
    pub created_at: DateTime<Utc>,
}

/// Structured finding representing a verified security vulnerability.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct Finding {
    /// Unique finding identifier
    pub finding_id: String,
    /// Violated invariant (e.g., I-01, I-02)
    pub invariant_id: InvariantId,
    /// Vulnerability title
    pub title: String,
    /// Detailed description of the business logic flaw
    pub description: String,
    /// Affected endpoint route pattern
    pub endpoint_pattern: String,
    /// Self-contained cURL reproduction command with sanitized parameters
    pub curl_poc: String,
    /// Automated retest assertion recipe confirming invariant restoration post-fix
    pub retest_assertion: String,
    /// Hash of the cryptographic ledger entry recording the proof
    pub evidence_ledger_hash: String,
    /// Finding confirmation timestamp
    pub discovered_at: DateTime<Utc>,
}

/// Errors relating to policy models.
#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum PolicyModelError {
    /// Unknown invariant identifier string
    #[error("Unknown security invariant: {0}")]
    InvalidInvariant(String),
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_invariant_id_parsing() {
        assert_eq!(InvariantId::from_str("I-01").unwrap(), InvariantId::I01);
        assert_eq!(InvariantId::from_str("I-02").unwrap(), InvariantId::I02);
        assert_eq!(format!("{}", InvariantId::I01), "I-01");
        assert!(InvariantId::from_str("UNKNOWN").is_err());
    }

    #[test]
    fn test_outgoing_request_serialization() {
        let req = OutgoingTestRequest {
            request_id: "req-101".to_string(),
            test_id: "test-bola-01".to_string(),
            target_url: "http://127.0.0.1:8000/api/v1/bookings/b-100".to_string(),
            method: "GET".to_string(),
            headers: HashMap::new(),
            body: None,
            tenant_context: None,
            credential_ref: Some("agency_b_agent".to_string()),
            invariant_candidate: Some(InvariantId::I01),
            timeout_ms: 3000,
        };

        let json = serde_json::to_string(&req).unwrap();
        assert!(json.contains("agency_b_agent"));
        assert!(json.contains("I-01"));

        let deserialized: OutgoingTestRequest = serde_json::from_str(&json).unwrap();
        assert_eq!(deserialized.request_id, "req-101");
        assert_eq!(deserialized.invariant_candidate, Some(InvariantId::I01));
    }
}
